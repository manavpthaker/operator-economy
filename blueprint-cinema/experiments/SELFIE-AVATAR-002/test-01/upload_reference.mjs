import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const base=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(base,'../../../..');
const target=path.resolve(base,'../media/reference/stone-polo-office-reference-v11.png');
const bytes=fs.readFileSync(target);
const sha=crypto.createHash('sha256').update(bytes).digest('hex');
if(sha!=='e8aa4f5b3d73f3341dbfa88a203a4decb8ee3c53cd890f6d9a3538a246d6412c')throw Error('Reference changed');
const receipt=path.join(base,'REFERENCE-UPLOAD.json');
if(fs.existsSync(receipt))throw Error('Upload already recorded');
fs.writeFileSync(path.join(base,'REFERENCE-UPLOAD-INTENT.json'),JSON.stringify({source:path.relative(repo,target),sha256:sha,owner_authorization:'Much better let’s try that',scope:'One upload of accepted still for video test',at:new Date().toISOString()},null,2)+'\n',{flag:'wx'});
const require=createRequire(path.join(repo,'blueprint-cinema/experiments/EP007-NET-NEW-UNFINISHED-ANSWER-003/hyperframes/reviews/r11-presenter-first/package.json'));
const {fal}=require('@fal-ai/client');
const line=fs.readFileSync(path.join(repo,'.env'),'utf8').split(/\r?\n/).find(x=>x.startsWith('FAL_KEY='));
if(!line)throw Error('FAL_KEY unavailable');
fal.config({credentials:line.slice(8).trim().replace(/^['"]|['"]$/g,'')});
const url=await fal.storage.upload(new File([bytes],'selfie-w2-lean-forward-v11.png',{type:'image/png'}));
fs.writeFileSync(receipt,JSON.stringify({url,sha256:sha,at:new Date().toISOString()},null,2)+'\n',{flag:'wx'});
const response=await fetch(url); if(!response.ok)throw Error('Readback failed');
const downloaded=Buffer.from(await response.arrayBuffer());
if(crypto.createHash('sha256').update(downloaded).digest('hex')!==sha)throw Error('Readback mismatch');
console.log(JSON.stringify({url,sha256:sha,readback_verified:true}));
