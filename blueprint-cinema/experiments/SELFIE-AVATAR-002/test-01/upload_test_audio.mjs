import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const base=path.dirname(fileURLToPath(import.meta.url)),repo=path.resolve(base,'../../../..');
const target=path.resolve(base,'../media/test-01/test01-original-c.wav'),bytes=fs.readFileSync(target);
const sha=crypto.createHash('sha256').update(bytes).digest('hex');
if(sha!=='2fda60f4b9f61fcb2f784ae311ce13f87525a484920e5a6d0079e0033b730609')throw Error('Source changed');
fs.writeFileSync(path.join(base,'AUDIO-UPLOAD-INTENT.json'),JSON.stringify({source:path.relative(repo,target),sha256:sha,scope:'One source-audio upload for approved opening test',at:new Date().toISOString()},null,2)+'\n',{flag:'wx'});
const require=createRequire(path.join(repo,'blueprint-cinema/experiments/EP007-NET-NEW-UNFINISHED-ANSWER-003/hyperframes/reviews/r11-presenter-first/package.json'));
const {fal}=require('@fal-ai/client');
const line=fs.readFileSync(path.join(repo,'.env'),'utf8').split(/\r?\n/).find(x=>x.startsWith('FAL_KEY='));
if(!line)throw Error('FAL_KEY unavailable');
fal.config({credentials:line.slice(8).trim().replace(/^['"]|['"]$/g,'')});
const url=await fal.storage.upload(new File([bytes],'selfie-w2-test01-original-c.wav',{type:'audio/wav'}));
const receipt={url,sha256:sha,at:new Date().toISOString()};
fs.writeFileSync(path.join(base,'AUDIO-UPLOAD.json'),JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
const response=await fetch(url);if(!response.ok)throw Error('Readback failed');
const check=Buffer.from(await response.arrayBuffer());
if(crypto.createHash('sha256').update(check).digest('hex')!==sha)throw Error('Readback mismatch');
console.log(JSON.stringify({...receipt,readback_verified:true}));
