import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const base=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(base,'../../../..');
const source=path.join(base,'media/macbook-reference.png');
const folder=path.join(base,'reference-upload');fs.mkdirSync(folder,{recursive:true});
const bytes=fs.readFileSync(source),sha256=crypto.createHash('sha256').update(bytes).digest('hex');
const save=(name,data)=>fs.writeFileSync(path.join(folder,name),JSON.stringify(data,null,2)+'\n',{flag:'wx'});
save('INTENT.json',{at:new Date().toISOString(),sha256,source:path.relative(repo,source),scope:'Upload generated reference for the authorized MacBook B-roll.'});
const req=createRequire(path.join(repo,'blueprint-cinema/experiments/EP007-NET-NEW-UNFINISHED-ANSWER-003/hyperframes/reviews/r11-presenter-first/package.json'));
const {fal}=req('@fal-ai/client');
const line=fs.readFileSync(path.join(repo,'.env'),'utf8').split(/\r?\n/).find(x=>x.startsWith('FAL_KEY='));
if(!line)throw Error('Scoped FAL_KEY unavailable');
fal.config({credentials:line.slice(8).trim().replace(/^['"]|['"]$/g,'')});
const file_url=await fal.storage.upload(new File([bytes],'week2-macbook-'+sha256.slice(0,16)+'.png',{type:'image/png'}));
save('RESPONSE.json',{at:new Date().toISOString(),file_url,sha256});
const r=await fetch(file_url);if(!r.ok)throw Error('Readback failed; inspect receipt before retry');
const check=Buffer.from(await r.arrayBuffer());
if(crypto.createHash('sha256').update(check).digest('hex')!==sha256)throw Error('Hosted image mismatch');
const record={at:new Date().toISOString(),file_url,sha256,size_bytes:bytes.length,status:'verified'};
save('UPLOAD.json',record);console.log(JSON.stringify(record));
