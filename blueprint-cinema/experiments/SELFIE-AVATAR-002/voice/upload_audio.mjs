import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const base=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(base,'../../../../');
const which=process.argv[2];
if(!['guide','final'].includes(which)) throw Error('guide, pickup, merged or final required');
const names={guide:'voice-w2.guide.wav',pickup:'voice-w2.pickup-guide.wav',merged:'voice-w2.corrected-guide.wav',final:'voice-w2.original-c.wav'};
const source=path.join(repo,'blueprint-cinema/experiments/SELFIE-AVATAR-002/media/voice',names[which]);
const folder=path.join(base,'W2',which+'-upload'); fs.mkdirSync(folder,{recursive:true});
const bytes=fs.readFileSync(source);
const hash=crypto.createHash('sha256').update(bytes).digest('hex');
const save=(name,data)=>fs.writeFileSync(path.join(folder,name),JSON.stringify(data,null,2)+'\n',{flag:'wx'});
save('INTENT.json',{at:new Date().toISOString(),source:path.relative(repo,source),sha256:hash,scope:'One upload of existing task audio; no generation'});
const req=createRequire(path.join(repo,'blueprint-cinema/experiments/EP007-NET-NEW-UNFINISHED-ANSWER-003/hyperframes/reviews/r11-presenter-first/package.json'));
const {fal}=req('@fal-ai/client');
const line=fs.readFileSync(path.join(repo,'.env'),'utf8').split(/\r?\n/).find(x=>x.startsWith('FAL_KEY='));
if(!line) throw Error('FAL_KEY unavailable');
const key=line.slice(8).trim().replace(/^['"]|['"]$/g,'');
fal.config({credentials:key});
const url=await fal.storage.upload(new File([bytes],'selfie-w2-'+which+'-'+hash.slice(0,16)+'.wav',{type:'audio/wav'}));
save('RESPONSE.json',{at:new Date().toISOString(),file_url:url,sha256:hash});
const response=await fetch(url); if(!response.ok) throw Error('Readback failed: '+response.status);
const check=Buffer.from(await response.arrayBuffer());
if(crypto.createHash('sha256').update(check).digest('hex')!==hash) throw Error('Readback hash mismatch');
const receipt={status:'verified',sha256:hash,file_url:url,size_bytes:bytes.length,at:new Date().toISOString()};
save('UPLOAD.json',receipt); console.log(JSON.stringify(receipt));

