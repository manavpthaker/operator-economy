// Mechanical trial checks, not a creative or publication approval.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(here,'../../../../../..');
const sum=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const probe=p=>JSON.parse(execFileSync('ffprobe',['-v','error','-show_streams','-show_format','-of','json',p],{encoding:'utf8'}));
const master=path.join(repo,'operator-blueprint-v2/episodes/EP007-exit-readiness-prep/02-narration-production/master/narration-master.v4.wav');
const audio=path.join(here,'public/audio/opening-narration.wav');
assert.equal(sum(master),'d8f7cb9630ae12ad427dca2c7bd1f29611f56c7985ce900ea312df3b9fec8da9');
assert.equal(sum(audio),'120c7a64ae8582f55f9bb4338c9ec276d763d79d88718aac482fc81c48ddbfb1');
assert.equal(sum(path.resolve(here,'../r6-character-first/index.html')),'2c129fe2918843395f495dc42a0b3a38e36afdd6b1b2b26c5d3c8d7f32a61772','R6 index changed');
const pcm=p=>execFileSync('ffmpeg',['-v','error','-i',p,'-af','atrim=start_sample=524160:end_sample=1340160,asetpts=PTS-STARTPTS','-c:a','pcm_s16le','-f','s16le','pipe:1'],{maxBuffer:4e6});
const trialPcm=pcm(audio);
assert.ok(trialPcm.equals(pcm(master)),'narration sample mismatch');
assert.equal(trialPcm.length,17*48000*2);
const html=fs.readFileSync(path.join(here,'index.html'),'utf8');
const attrs=s=>Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map(m=>[m[1],m[2]]));
const shots=[...html.matchAll(/<video\s([^>]+)>/g)].map(m=>attrs(m[1]));
const vo=attrs(html.match(/<audio\s([^>]+)>/)[1]);
assert.equal(shots.length,2);
assert.equal(Number(vo['data-media-start']),10.92);
assert.equal(Number(vo['data-duration']),17);
assert.equal(Number(vo['data-start']),0);
assert.equal(Number(vo['data-volume']),1);
assert.ok(!/<svg|<canvas|<img|data-playback-rate|data-composition-src|\.play\(/.test(html));
const ids=[...html.matchAll(/\sid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length);
let cursor=0;
const results=[];
for(const [i,t] of shots.entries()){
  const letter=i===0?'a':'b';
  const file=path.join(here,t.src);
  const source=path.join(here,'renders/candidates/shot-'+letter+'.mp4');
  const receipt=JSON.parse(fs.readFileSync(source+'.response.json','utf8'));
  const info=probe(file), video=info.streams.find(s=>s.codec_type==='video');
  const start=Number(t['data-start']), duration=Number(t['data-duration']), mediaStart=Number(t['data-media-start']);
  assert.ok(Math.abs(start-cursor)<1e-8);
  assert.equal(t['data-track-index'],'1');
  assert.equal(t['data-playback-rate'],undefined);
  assert.ok(info.streams.every(s=>s.codec_type!=='audio'));
  assert.equal(video.r_frame_rate,'24/1');
  assert.ok(mediaStart>=0 && mediaStart+duration<=Number(video.duration));
  assert.equal(sum(file),sum(source));
  assert.equal(sum(file),receipt.output.sha256);
  assert.equal(sum(receipt.request.reference),receipt.request.referenceSha256);
  assert.equal(receipt.model,'fal-ai/kling-video/v3/pro/image-to-video');
  assert.equal(receipt.request.parameters.generate_audio,false);
  assert.equal(receipt.request.parameters.cfg_scale,0.5);
  assert.equal(Number(receipt.request.parameters.duration),i===0?11:8);
  assert.equal(receipt.request.parameters.end_image_url,undefined);
  const prompt=fs.readFileSync(receipt.request.promptRecord,'utf8').match(/## Prompt\s+([\s\S]*?)(?=\n## |$)/)[1].trim();
  assert.ok(prompt.length<=2500);
  results.push({id:letter,sha256:sum(file),requestId:receipt.requestId,source:[mediaStart,mediaStart+duration],record:[start,start+duration],sourceDuration:Number(video.duration),width:video.width,height:video.height,fps:video.r_frame_rate});
  cursor+=duration;
}
assert.equal(cursor,17);
const result={status:'mechanical-trial-check-passed',duration:17,frames:408,fps:24,narrationSource:[10.92,27.92],narrationPcmSha256:crypto.createHash('sha256').update(trialPcm).digest('hex'),shots:results,estimatedVideoListCostUsd:2.128,billingInvoiceVerified:false,creativeApproval:false,productionGateAdvance:false,finalRender:false,limitations:['Mechanical validation and sampled frames do not establish dramatic effectiveness.','Reference-image generation cost is separate and unverified.','User review and full-opening expansion remain pending.']};
fs.writeFileSync(path.join(here,'renders/verification.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
