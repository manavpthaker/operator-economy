"""
Flip an episode live on the site by writing its episode URL into the registry.

The site reads episode URLs from `site/data/episode-urls.json`. This script is the
only writer of that file, and it never invents a URL: it copies `episode_url` out of
`studio/originate/<slug>/launch/links.json`, which per the project rule is the only
place an episode URL may originate.

`site/app/lib/operations.ts` resolves each operation's `youtubeUrl` from that registry.
An empty URL is the pre-publish state: the Canvas page states the publication month and
the home page reads "Scheduled" instead of linking nowhere. A non-empty URL is live.

Before 2026-10-12 this script wrote `site/data/episodes.json`, which no longer drives the
library. That file is left alone here; it is still read by the content-os release audit
and by the legacy `LatestBlueprint` helpers.

Usage:
    python scripts/originate/publish.py <slug>              # flip live (the launch-day step)
    python scripts/originate/publish.py <slug> --register   # pre-seed the entry, URL stays empty
    python scripts/originate/publish.py <slug> --unpublish   # clear the URL, back to pre-publish
    python scripts/originate/publish.py <slug> --dry-run    # print the change, write nothing
    python scripts/originate/publish.py <slug> --notify     # also email notify:<slug> subscribers

This script does not deploy. Production builds from `main`, so the flip only reaches the
site once its commit is on `main`; the script prints the remaining steps when it finishes.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent.parent.parent
ORIGINATE = REPO_ROOT / "studio" / "originate"
REGISTRY = REPO_ROOT / "site" / "data" / "episode-urls.json"
OPERATIONS_TS = REPO_ROOT / "site" / "app" / "lib" / "operations.ts"

REGISTRY_HEADER = {
    "_generated_by": "studio/scripts/originate/publish.py",
    "_source": "studio/originate/<slug>/launch/links.json (episode_url)",
    "_warning": (
        "Do not hand-edit. Only launch/links.json may originate an episode URL; this file "
        "is a copy of it. site/app/lib/operations.ts reads episodes.<slug>.url, and an empty "
        "url is the pre-publish state."
    ),
}

# Matches `slug: 'direct-booking-practice',` in operations.ts. Read-only: this script never
# writes TypeScript. Used to fail closed on a slug the site does not actually publish.
SLUG_RE = re.compile(r"^\s*slug:\s*'([a-z0-9-]+)',\s*$", re.M)


def die(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def load_json(path: Path, label: str) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        die(f"{label} not found: {path.relative_to(REPO_ROOT)}")
    except json.JSONDecodeError as exc:
        die(f"{label} is not valid JSON ({path.relative_to(REPO_ROOT)}): {exc}")
    return {}  # unreachable; keeps type checkers quiet


def site_slugs() -> set[str]:
    """The operation slugs the site publishes, read out of operations.ts.

    A read-only scan. If the file's shape ever changes enough that no slug matches, this
    fails rather than silently accepting any slug.
    """
    if not OPERATIONS_TS.exists():
        die(f"{OPERATIONS_TS.relative_to(REPO_ROOT)} not found — is this the OE repo root?")
    slugs = set(SLUG_RE.findall(OPERATIONS_TS.read_text(encoding="utf-8")))
    if not slugs:
        die(
            f"found no operation slugs in {OPERATIONS_TS.relative_to(REPO_ROOT)}; its shape "
            "changed and this script's reader needs updating"
        )
    return slugs


def episode_url_from_links(slug: str) -> tuple[str, str]:
    """Return (episode_url, title) from the episode's launch/links.json."""
    links = load_json(ORIGINATE / slug / "launch" / "links.json", "launch/links.json")

    if links.get("slug") not in (None, slug):
        die(f"launch/links.json is for slug '{links.get('slug')}', not '{slug}'")
    if links.get("dry_run"):
        die("launch/links.json was generated by a dry run — the upload has not really happened")

    url = str(links.get("episode_url") or "").strip()
    if not url.startswith("http") or "PENDING" in url:
        die(f"launch/links.json has no real episode_url (got {url!r}) — run the upload first")

    return url, str(links.get("title") or "the episode").strip()


def publication_number(slug: str, override: int | None) -> int:
    """The public number, from release.json, then --number, then the Canvas filename."""
    if override is not None:
        return override

    release_path = ORIGINATE / slug / "release.json"
    if release_path.exists():
        release = load_json(release_path, "release.json")
        if release.get("slug") not in (None, slug):
            die(f"release.json is for slug '{release.get('slug')}', not '{slug}'")
        number = release.get("publication_number")
        if isinstance(number, int) and number > 0:
            return number

    # No release record (EP008 never got one). Fall back to the Canvas artifact's number.
    for pdf in sorted((ORIGINATE / slug).glob("Operator-Canvas-*.pdf")):
        match = re.search(r"Operator-Canvas-(\d+)\.pdf$", pdf.name)
        if match:
            return int(match.group(1))

    die(f"cannot determine the public number for '{slug}' — pass --number")
    return 0  # unreachable


def read_registry() -> dict:
    if not REGISTRY.exists():
        return {**REGISTRY_HEADER, "updated": date.today().isoformat(), "episodes": {}}
    data = load_json(REGISTRY, "episode URL registry")
    if not isinstance(data.get("episodes"), dict):
        die(f"{REGISTRY.relative_to(REPO_ROOT)} has no 'episodes' object")
    return data


def write_registry(data: dict) -> None:
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    data.update(REGISTRY_HEADER)
    data["updated"] = date.today().isoformat()
    # Newest public number first, so the file reads like the library does.
    data["episodes"] = dict(
        sorted(data["episodes"].items(), key=lambda kv: kv[1].get("number", 0), reverse=True)
    )
    REGISTRY.write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def _notify_subscribers(slug: str, number: int, title: str) -> None:
    """Fire the "№00X is live" email to notify:{slug} subscribers via Resend.

    Requires RESEND_API_KEY, RESEND_FROM, and DATABASE_URL in the environment.
    Prints the recipient count and asks for confirmation before sending.
    """
    try:
        import psycopg
        import resend  # 2.x: module-level api_key + resend.Emails.send({...})
    except ImportError as e:
        print(f"error: notify requires psycopg + resend Python packages ({e})", file=sys.stderr)
        print("  pip install 'psycopg[binary]' resend", file=sys.stderr)
        sys.exit(1)

    db_url = os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL")
    resend_key = os.environ.get("RESEND_API_KEY")
    resend_from = os.environ.get("RESEND_FROM", "The Operator Economy <hello@theoperatoreconomy.com>")
    # Fallback = the production domain, not the vercel.app preview. If the
    # env var is set but malformed (shipped once as `https://theoperatoreconomy.`
    # — no `.com`), also fall back so we don't leak broken URLs into notify
    # emails.
    _raw = os.environ.get("NEXT_PUBLIC_SITE_URL", "").strip()
    site_url = _raw if re.match(r"^https?://[a-z0-9-]+(\.[a-z0-9-]+)+/?$",
                                _raw, re.I) else "https://theoperatoreconomy.com"
    site_url = site_url.rstrip("/")
    if not db_url or not resend_key:
        print("error: DATABASE_URL and RESEND_API_KEY must be set for --notify", file=sys.stderr)
        sys.exit(1)

    tag = f"notify:{slug}"
    with psycopg.connect(db_url) as conn:
        with conn.cursor() as cur:
            cur.execute(
                "select email, unsubscribe_token from subscribers where tag = %s and unsubscribed_at is null",
                (tag,),
            )
            rows = cur.fetchall()

    if not rows:
        print(f"No active notify:{slug} subscribers — nothing to send.")
        return

    num = f"{number:03d}"
    # The operation page, not /episodes/<slug>: that form is a permanent redirect now.
    ep_url = f"{site_url}/businesses/{slug}"

    print(f"About to email {len(rows)} subscribers that №{num} is live.")
    confirm = input("Send now? [y/N] ").strip().lower()
    if confirm != "y":
        print("Aborted.")
        return

    resend.api_key = resend_key
    sent = 0
    for email, token in rows:
        unsub = f"{site_url}/api/unsubscribe?token={token}"
        try:
            resend.Emails.send(
                {
                    "from": resend_from,
                    "to": email,
                    "subject": f"№{num} is live — {title}",
                    "text": (
                        f"It shipped.\n\n"
                        f"№{num} — \"{title}\" — is live: {ep_url}\n\n"
                        f"The Operator Canvas (PDF), full sources, and the model's arithmetic are on the page.\n\n"
                        f"You're on the Monday note. Unsubscribe any time: {unsub}\n\n"
                        f"— The Operator Economy"
                    ),
                }
            )
            sent += 1
        except Exception as e:
            print(f"  ! failed to send to {email}: {e}", file=sys.stderr)

    print(f"✓ notified {sent}/{len(rows)} subscribers")


def main():
    parser = argparse.ArgumentParser(description="Flip an episode live on the site")
    parser.add_argument("slug", help="Episode slug (matches the site's operation slug)")
    parser.add_argument("--number", type=int, help="Public number, if release.json has none")
    parser.add_argument(
        "--register",
        action="store_true",
        help="Create/refresh the entry but leave the URL empty (pre-publish state)",
    )
    parser.add_argument("--unpublish", action="store_true", help="Clear the URL, back to pre-publish")
    parser.add_argument("--dry-run", action="store_true", help="Print the change, write nothing")
    parser.add_argument(
        "--notify",
        action="store_true",
        help="After the flip, email notify:{slug} subscribers via Resend",
    )
    args = parser.parse_args()
    slug = args.slug

    if args.register and args.unpublish:
        die("--register and --unpublish do the same thing; pass one")

    known = site_slugs()
    if slug not in known:
        die(
            f"'{slug}' is not an operation on the site. operations.ts publishes: "
            + ", ".join(sorted(known))
        )

    if not (ORIGINATE / slug).is_dir():
        die(f"no episode directory: studio/originate/{slug}")

    # Read the URL even when clearing it, so the entry's number/title stay accurate and a
    # missing or dry-run links.json is caught in every mode.
    url, title = episode_url_from_links(slug)
    number = publication_number(slug, args.number)
    clearing = args.register or args.unpublish

    data = read_registry()
    before = data["episodes"].get(slug, {})
    entry = {
        "number": number,
        "title": title,
        "status": "scheduled" if clearing else "live",
        "url": "" if clearing else url,
    }

    if before == entry:
        print(f"= {slug} already recorded as {entry['status']} (№{number:03d}) — nothing to change.")
        if args.notify and not clearing:
            _notify_subscribers(slug, number, title)
        return

    was = before.get("url") or "(none)"
    print(f"  {REGISTRY.relative_to(REPO_ROOT)}: {slug}")
    print(f"    number  {before.get('number', '—')} → {number}")
    print(f"    status  {before.get('status', '—')} → {entry['status']}")
    print(f"    url     {was} → {entry['url'] or '(none)'}")

    if args.dry_run:
        print("\n--dry-run: nothing written.")
        return

    data["episodes"][slug] = entry
    write_registry(data)

    if clearing:
        print(f"\n✓ {slug} recorded as scheduled №{number:03d} — the site shows it as pre-publish.")
        return

    print(f"\n✓ {slug} flipped live as №{number:03d}")
    print("  The site reads this at build time, and production builds from `main`. Still to do:")
    print(f"    1. commit {REGISTRY.relative_to(REPO_ROOT)}")
    print("    2. get that commit onto `main` (Vercel deploys `main` on push)")
    print("    3. confirm https://theoperatoreconomy.com/businesses/%s links the video" % slug)

    if args.notify:
        _notify_subscribers(slug, number, title)


if __name__ == "__main__":
    main()
